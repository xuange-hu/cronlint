"""Generate the rule table document.

`docs/rules.md` is produced from this module, never edited by hand, and CI
regenerates it and diffs. The generator therefore has to be deterministic:
rules in id order, no timestamps, no host paths.
"""

from __future__ import annotations

from .rules import REGISTRY, Rule

_STAGE_NAME = {1: "expression", 2: "task", 3: "file"}


def _sorted() -> list[Rule]:
    return sorted(REGISTRY, key=lambda item: item.id)


def brief_markdown() -> str:
    """A compact table: id, severity, stage, title."""
    lines = [
        "| Id | Severity | Stage | Rule |",
        "|---|---|---|---|",
    ]
    for item in _sorted():
        stage = _STAGE_NAME.get(item.stage, str(item.stage))
        lines.append(f"| `{item.id}` | {item.severity} | {stage} | {item.title} |")
    return "\n".join(lines) + "\n"


def full_markdown() -> str:
    """The whole table: every rule with why it matters and how to fix it."""
    table = _sorted()
    counts: dict[str, int] = {}
    for item in table:
        counts[item.severity] = counts.get(item.severity, 0) + 1

    lines = [
        "# Rule reference",
        "",
        f"{len(table)} rules across three passes. Generated by "
        "`cronlint rules --markdown`; do not edit by hand.",
        "",
        "Severity counts: "
        + ", ".join(f"{name} {counts.get(name, 0)}" for name in ("critical", "high", "medium", "low", "note")),
        "",
        brief_markdown().rstrip(),
        "",
    ]

    for stage in (1, 2, 3):
        stage_rules = [item for item in table if item.stage == stage]
        if not stage_rules:
            continue
        lines.append(f"## Pass {stage}: {_STAGE_NAME[stage]}")
        lines.append("")
        for item in stage_rules:
            lines.append(f"### `{item.id}` — {item.title}")
            lines.append("")
            lines.append(f"**Severity** {item.severity} (score {item.score})")
            lines.append("")
            lines.append(item.why)
            lines.append("")
            lines.append(f"**Fix.** {item.fix}")
            lines.append("")

    return "\n".join(lines)
